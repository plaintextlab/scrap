"""Regenerates the launcher <activity-alias> entries in AndroidManifest.xml.

One alias per launcher name (Settings > App name) and colour theme, each with its own label
and icon; LauncherName.kt enables exactly one. Gruvbox aliases keep their original names
(".LauncherNotes") so existing installs keep their choice. Run after changing the names or
themes here, in LauncherName.kt or in ThemeName (Settings.kt):

    python android/launcher-aliases.py
"""

import os
import re

NAMES = ["Scrap", "Notes", "Notebook", "Journal", "Wiki", "Vault", "Memo"]
# (enum name in ThemeName, icon id from packaging/make-icons.py)
THEMES = [
    ("Gruvbox", "gruvbox"),
    ("Everforest", "everforest"),
    ("Nord", "nord"),
    ("Catppuccin", "catppuccin"),
    ("Solarized", "solarized"),
    ("TokyoNight", "tokyonight"),
]
MANIFEST = os.path.join(os.path.dirname(os.path.abspath(__file__)), "app", "src", "main", "AndroidManifest.xml")
BEGIN = "<!-- BEGIN launcher aliases: generated by android/launcher-aliases.py -->"
END = "<!-- END launcher aliases -->"


def aliases() -> str:
    out = [BEGIN]
    for theme, icon in THEMES:
        for name in NAMES:
            suffix = "" if theme == "Gruvbox" else theme
            enabled = "true" if (name, theme) == ("Scrap", "Gruvbox") else "false"
            out.append(f"""        <activity-alias
            android:name=".Launcher{name}{suffix}"
            android:enabled="{enabled}"
            android:exported="true"
            android:icon="@mipmap/ic_launcher_{icon}"
            android:label="{name}"
            android:targetActivity=".MainActivity">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>""")
    out.append("        " + END)
    return "\n".join(out)


def main() -> None:
    s = open(MANIFEST, encoding="utf-8").read()
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: aliases(), s, flags=re.S)
    else:
        # First run: replace the hand-written aliases.
        start = s.index("        <!-- Launcher entries")
        end = s.index("        <!-- Hands the camera app")
        s = s[:start] + "        " + aliases() + "\n\n" + s[end:]
    open(MANIFEST, "w", encoding="utf-8", newline="\n").write(s)


if __name__ == "__main__":
    main()
