"""Regenerates the app icons for every colour theme.

Desktop: the Phosphor "note-pencil" glyph in the theme's accent colour on its dark
background. Writes packaging/icons/scrap.{png,ico,icns} (Gruvbox, the installed icon) and
packaging/icons/themes/<theme>.png (window icons, swapped at runtime by theme::apply).

Android: an adaptive launcher icon per theme (vector glyph, same colours) in
android/app/src/main/res, used by the launcher aliases in AndroidManifest.xml.

Needs Pillow and the Phosphor font that the egui-phosphor crate ships:
    python packaging/make-icons.py path/to/Phosphor-Bold.ttf
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

# (id, dark background, accent): the dark palettes in src/theme.rs.
THEMES = [
    ("gruvbox", "#282828", "#FABD2F"),
    ("everforest", "#2D353B", "#A7C080"),
    ("nord", "#2E3440", "#88C0D0"),
    ("catppuccin", "#1E1E2E", "#CBA6F7"),
    ("solarized", "#002B36", "#268BD2"),
    ("tokyonight", "#1A1B26", "#7AA2F7"),
]
NOTE_PENCIL = ""
HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.join(HERE, "icons")
RES = os.path.join(HERE, "..", "android", "app", "src", "main", "res")

# Material "description" glyph for Android's vector icon.
ANDROID_GLYPH = (
    "M14,2H6c-1.1,0 -1.99,0.9 -1.99,2L4,20c0,1.1 0.89,2 1.99,2H18c1.1,0 2,-0.9 2,-2V8l-6,-6z"
    "M16,18H8v-2h8v2zM16,14H8v-2h8v2zM13,9V3.5L18.5,9H13z"
)


def rgb(hex_color: str) -> tuple:
    h = hex_color.lstrip("#")
    return tuple(int(h[i : i + 2], 16) for i in (0, 2, 4)) + (255,)


def icon(size: int, font_path: str, bg: str, accent: str) -> Image.Image:
    # Draw large and scale down for smooth edges.
    big = size * 4
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    margin = big * 0.06
    d.rounded_rectangle([margin, margin, big - margin, big - margin], radius=big * 0.22, fill=rgb(bg))
    font = ImageFont.truetype(font_path, int(big * 0.58))
    d.text((big / 2, big / 2), NOTE_PENCIL, font=font, fill=rgb(accent), anchor="mm")
    return img.resize((size, size), Image.LANCZOS)


def android(theme: str, bg: str, accent: str) -> None:
    fg = os.path.join(RES, "drawable", f"ic_launcher_foreground_{theme}.xml")
    with open(fg, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/make-icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="2.25"
        android:scaleY="2.25"
        android:translateX="27"
        android:translateY="27">
        <path
            android:fillColor="{accent}"
            android:pathData="{ANDROID_GLYPH}" />
    </group>
</vector>
""")
    adaptive = os.path.join(RES, "mipmap-anydpi-v26", f"ic_launcher_{theme}.xml")
    with open(adaptive, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by packaging/make-icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/launcher_bg_{theme}" />
    <foreground android:drawable="@drawable/ic_launcher_foreground_{theme}" />
    <monochrome android:drawable="@drawable/ic_launcher_foreground_{theme}" />
</adaptive-icon>
""")


def main() -> None:
    font = sys.argv[1]
    os.makedirs(os.path.join(ICONS, "themes"), exist_ok=True)
    for theme, bg, accent in THEMES:
        master = icon(1024, font, bg, accent)
        master.resize((256, 256), Image.LANCZOS).save(os.path.join(ICONS, "themes", f"{theme}.png"), optimize=True)
        if theme == "gruvbox":
            master.resize((512, 512), Image.LANCZOS).save(os.path.join(ICONS, "scrap.png"), optimize=True)
            master.resize((256, 256), Image.LANCZOS).save(
                os.path.join(ICONS, "scrap.ico"),
                sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)],
            )
            master.save(os.path.join(ICONS, "scrap.icns"))
        android(theme, bg, accent)
    colors = os.path.join(RES, "values", "launcher_colors.xml")
    with open(colors, "w", encoding="utf-8", newline="\n") as f:
        f.write("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n<!-- Generated by packaging/make-icons.py. -->\n<resources>\n")
        for theme, bg, _ in THEMES:
            f.write(f'    <color name="launcher_bg_{theme}">{bg}</color>\n')
        f.write("</resources>\n")


if __name__ == "__main__":
    main()
